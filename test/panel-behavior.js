const path = require('path');
const os = require('os');
const assert = require('node:assert/strict');
const { app, BrowserWindow } = require('electron');
app.setPath('userData', path.join(os.tmpdir(), 'cue-behavior-' + process.pid));
process.env.CUE_DOCUMENTS_DIR = path.join(os.tmpdir(), 'cue-behavior-docs-' + process.pid);
require('../main');
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
app.whenReady().then(async () => {
  try {
    let win;
    for (let i = 0; i < 100; i++) {
      win = BrowserWindow.getAllWindows()[0];
      if (win && !win.webContents.isLoading()) break;
      await pause(100);
    }
    win.setSize(1600, 980);
    await pause(500);
    win.webContents.debugger.attach('1.3');
    await win.webContents.debugger.sendCommand('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'no-preference' }] });
    const run = code => win.webContents.executeJavaScript(code);
    const rect = id => run(`document.getElementById('${id}').getBoundingClientRect().toJSON()`);
    const drag = async (handle, dx, dy) => {
      const r = await rect(handle);
      const x = Math.round(r.x + r.width / 2), y = Math.round(r.y + r.height / 2);
      win.webContents.sendInputEvent({ type: 'mouseMove', x, y });
      win.webContents.sendInputEvent({ type: 'mouseDown', button: 'left', x, y, clickCount: 1, modifiers: ['leftButtonDown'] });
      for (let i = 1; i <= 5; i++) {
        win.webContents.sendInputEvent({ type: 'mouseMove', x: x + Math.round(dx * i / 5), y: y + Math.round(dy * i / 5), modifiers: ['leftButtonDown'] });
        await pause(20);
      }
      win.webContents.sendInputEvent({ type: 'mouseUp', button: 'left', x: x + dx, y: y + dy, clickCount: 1 });
      await pause(100);
    };
    await run(`document.getElementById('ob-skip').click()`);
    await pause(300);
    const initial = await rect('panel-wrap');
    await drag('panel-topbar', 90, 80);
    const moved = await rect('panel-wrap');
    assert(Math.abs(moved.x - initial.x - 90) < 2 && Math.abs(moved.y - initial.y - 80) < 2, 'main panel moves with mouse input');
    const saved = await run(`cue.settingsGet()`);
    assert.deepEqual(saved.appearance.panelPositions.panel, { x: 90, y: 80 });
    win.webContents.reload();
    await pause(800);
    const restored = await rect('panel-wrap');
    assert(Math.abs(restored.x - moved.x) < 2 && Math.abs(restored.y - moved.y) < 2, 'positions survive renderer reload');
    await run(`document.getElementById('more-btn').click()`);
    await pause(60);
    assert(await run(`document.getElementById('settings-scrim').getAnimations().some(a => a.playState === 'running')`), 'opening animates');
    assert(await run(`(() => { const opacity=Number(getComputedStyle(document.getElementById('settings-scrim')).opacity); return opacity>0 && opacity<1; })()`), 'opening visibly interpolates opacity');
    await pause(300);
    await run(`document.querySelector('#settings .s-head').id='settings-drag-test'`);
    const settingsBefore = await rect('settings-scrim');
    await drag('settings-drag-test', -70, 90);
    const settingsAfter = await rect('settings-scrim');
    assert(Math.abs(settingsAfter.x - settingsBefore.x + 70) < 2 && Math.abs(settingsAfter.y - settingsBefore.y - 90) < 2, 'settings header drags independently');
    assert.deepEqual(await rect('panel-wrap'), restored, 'settings drag leaves main panel in place');
    await run(`document.getElementById('settings-interface-tab').click()`);
    await pause(60);
    assert(await run(`document.getElementById('settings-interface-pane').getAnimations().length > 0`), 'tab switch animates');
    await pause(300);
    await run(`document.getElementById('appearance-drag').click()`);
    const frozen = await rect('settings-scrim');
    await drag('settings-drag-test', -60, 50);
    assert.deepEqual(await rect('settings-scrim'), frozen, 'drag switch disables movement');
    await run(`document.getElementById('appearance-animations').click()`);
    assert(await run(`(() => {
      const line=document.createElement('div'); line.className='ai-text'; line.innerHTML='<span class="w">Visible answer</span>';
      document.body.append(line); const visible=getComputedStyle(line.firstChild).opacity==='1'; line.remove(); return visible;
    })()`), 'answers remain visible with animations off');
    await run(`document.getElementById('settings-provider-tab').click()`);
    assert(await run(`document.getElementById('settings-provider-pane').getAnimations().length === 0`), 'disabled motion is immediate');
    await run(`document.getElementById('settings-interface-tab').click(); document.getElementById('appearance-animations').click()`);
    await pause(300);
    await run(`document.getElementById('s-close').click()`);
    await pause(60);
    assert(await run(`document.getElementById('settings-scrim').classList.contains('hidden') && document.getElementById('settings-scrim').getAnimations().some(a => a.playState === 'running')`), 'closing animates after successful save');
    await pause(300);
    assert(await run(`getComputedStyle(document.getElementById('settings-scrim')).display === 'none'`));
    await run(`document.getElementById('more-btn').click()`);
    await pause(300);
    await run(`document.getElementById('settings-interface-tab').click(); document.getElementById('appearance-drag').click(); document.getElementById('panel-positions-reset').click()`);
    await pause(300);
    const reset = await rect('panel-wrap');
    assert(Math.abs(reset.x-initial.x)<2 && Math.abs(reset.y-initial.y)<2, 'reset restores original placement');
    assert.deepEqual((await run(`cue.settingsGet()`)).appearance.panelPositions, {});
    await run(`document.getElementById('s-close').click()`);
    await pause(300);
    const toolbarBefore = await rect('toolbar');
    await drag('mic-activity', -80, 60);
    const toolbarAfter = await rect('toolbar');
    assert(Math.abs(toolbarAfter.x-toolbarBefore.x+80)<2 && Math.abs(toolbarAfter.y-toolbarBefore.y-60)<2, 'toolbar drags by center');
    await run(`document.getElementById('search-btn').click(); document.querySelector('#catalog .s-head').id='catalog-drag-test'`);
    await pause(300);
    const catalogBefore = await rect('catalog-scrim');
    await drag('catalog-drag-test', 50, 70);
    const catalogAfter = await rect('catalog-scrim');
    assert(Math.abs(catalogAfter.x-catalogBefore.x-50)<2 && Math.abs(catalogAfter.y-catalogBefore.y-70)<2, 'catalog drags by header');
    await run(`document.getElementById('logo-btn').click()`);
    await pause(300);
    const onboardBefore = await rect('onboard');
    await drag('ob-dots', 50, 70);
    const onboardAfter = await rect('onboard');
    assert(Math.abs(onboardAfter.x-onboardBefore.x-50)<2 && Math.abs(onboardAfter.y-onboardBefore.y-70)<2, 'onboarding drags by dots area');
    await drag('ob-dots', -80, -90);
    const clamped = await rect('onboard');
    assert(clamped.left>=40 && clamped.top>=40, 'drag preserves shadow gutter');
    await run(`document.getElementById('more-btn').click(); document.getElementById('settings-interface-tab').click()`);
    await pause(300);
    await win.webContents.debugger.sendCommand('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'reduce' }] });
    await pause(100);
    assert(await run(`document.documentElement.dataset.animations === 'off' && document.getElementById('motion-hint').textContent.includes('системной')`), 'system reduced-motion explained');
    console.log('PASS: real pointer dragging, independent panels, persistence, disabled dragging, reset, enter/exit/tab animations, disabled and reduced motion.');
    app.exit(0);
  } catch (error) { console.error(error.stack); app.exit(1); }
});
setTimeout(() => app.exit(1), 30000).unref();
